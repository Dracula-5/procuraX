"""Object storage for invoice files, behind one small interface.

`LocalStorage` (development) writes under a directory; `S3Storage` talks to any S3-compatible service
(MinIO locally and in CI, AWS S3 or Cloudflare R2 in production). Objects are write-once: `put` refuses
to replace an existing key, so a stored file can never be swapped underneath its recorded SHA-256.
Keys are generated by the application (tenant prefix + random id) and never contain the uploaded name.
"""

import asyncio
import os
from pathlib import Path
from typing import Any, Protocol
from urllib.parse import quote

from app.core.config import Settings, get_settings


class StorageError(RuntimeError):
    pass


class ObjectExistsError(StorageError):
    pass


class ObjectStorage(Protocol):
    async def put(self, key: str, data: bytes, content_type: str) -> None: ...

    async def get(self, key: str) -> bytes: ...

    async def presigned_url(self, key: str, *, filename: str, content_type: str) -> str | None:
        """A short-lived download URL, or None when the API should stream the bytes itself."""
        ...


def _safe_key(key: str) -> str:
    parts = key.split("/")
    if not key or key.startswith("/") or any(p in {"", ".", ".."} for p in parts):
        raise StorageError(f"Invalid object key: {key!r}")
    return key


class LocalStorage:
    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / _safe_key(key)).resolve()
        if self.root not in path.parents:
            raise StorageError(f"Invalid object key: {key!r}")
        return path

    def _put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        try:
            # O_EXCL: fail instead of replacing an existing object (write-once).
            fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_BINARY", 0), 0o600)
        except FileExistsError as exc:
            raise ObjectExistsError(key) from exc
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        await asyncio.to_thread(self._put, key, data)

    async def get(self, key: str) -> bytes:
        try:
            return await asyncio.to_thread(self._path(key).read_bytes)
        except FileNotFoundError as exc:
            raise StorageError(f"Object not found: {key}") from exc

    async def presigned_url(self, key: str, *, filename: str, content_type: str) -> str | None:
        return None


class S3Storage:
    def __init__(self, settings: Settings) -> None:
        import boto3
        from botocore.config import Config

        self.settings = settings
        self.bucket = settings.s3_bucket
        self.client: Any = boto3.client(
            "s3",
            endpoint_url=settings.s3_endpoint_url,
            region_name=settings.s3_region,
            aws_access_key_id=settings.s3_access_key_id,
            aws_secret_access_key=settings.s3_secret_access_key,
            # Path-style addressing works with MinIO and AWS alike; bounded retries and timeouts.
            config=Config(
                signature_version="s3v4",  # SigV4 everywhere: AWS rejects SigV2 presigned URLs in newer regions
                s3={"addressing_style": "path"},
                retries={"max_attempts": 3},
                connect_timeout=5,
                read_timeout=30,
            ),
        )

    def _put(self, key: str, data: bytes, content_type: str) -> None:
        from botocore.exceptions import ClientError

        try:
            # If-None-Match: * makes the write conditional: an existing key is never overwritten.
            self.client.put_object(
                Bucket=self.bucket, Key=_safe_key(key), Body=data, ContentType=content_type, IfNoneMatch="*"
            )
        except ClientError as exc:
            code = exc.response.get("Error", {}).get("Code", "")
            if code in {"PreconditionFailed", "ConditionalRequestConflict"}:
                raise ObjectExistsError(key) from exc
            raise StorageError(f"S3 put failed: {code or exc}") from exc

    def _get(self, key: str) -> bytes:
        from botocore.exceptions import ClientError

        try:
            body: bytes = self.client.get_object(Bucket=self.bucket, Key=_safe_key(key))["Body"].read()
            return body
        except ClientError as exc:
            raise StorageError(f"S3 get failed: {exc.response.get('Error', {}).get('Code', exc)}") from exc

    def ensure_bucket(self) -> bool:
        """Create the bucket if it does not exist (local/CI setup). Returns True when it was created."""
        from botocore.exceptions import ClientError

        try:
            self.client.head_bucket(Bucket=self.bucket)
            return False
        except ClientError:
            self.client.create_bucket(Bucket=self.bucket)
            return True

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        await asyncio.to_thread(self._put, key, data, content_type)

    async def get(self, key: str) -> bytes:
        return await asyncio.to_thread(self._get, key)

    async def presigned_url(self, key: str, *, filename: str, content_type: str) -> str | None:
        if not self.settings.s3_presign_downloads:
            return None
        # RFC 6266/5987: an ASCII fallback plus the exact UTF-8 name (Japanese file names survive).
        ascii_name = filename.encode("ascii", "replace").decode().replace('"', "").replace("?", "_")
        disposition = f"attachment; filename=\"{ascii_name}\"; filename*=UTF-8''{quote(filename)}"
        url: str = await asyncio.to_thread(
            self.client.generate_presigned_url,
            "get_object",
            Params={
                "Bucket": self.bucket,
                "Key": _safe_key(key),
                "ResponseContentType": content_type,
                "ResponseContentDisposition": disposition,
            },
            ExpiresIn=self.settings.s3_presign_seconds,
        )
        return url


def get_storage(settings: Settings | None = None) -> ObjectStorage:
    settings = settings or get_settings()
    if settings.storage_backend == "s3":
        return S3Storage(settings)
    return LocalStorage(settings.storage_local_dir)
